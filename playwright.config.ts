import { defineConfig } from '@playwright/test'

/**
 * Браузерный смоук: собранный сайт от лендинга до скачанного альбома.
 *
 * Всё остальное в проекте проверяется без браузера — движок своими тестами,
 * разметка через renderToStaticMarkup. Это ловит расчёт и содержимое, но не
 * ловит того, что путь пользователя разорван: не подхватился словарь, упал
 * воркер, не открылась страница проекта. Такое видно только в браузере.
 *
 * Прогон требует собранного фронтенда и тестового пользователя. Без них тест
 * пропускается с причиной — тихого успеха здесь быть не должно.
 */
export default defineConfig({
  testDir: 'e2e',
  timeout: 120_000,
  expect: { timeout: 20_000 },
  // Один браузер: смоук отвечает на вопрос «путь цел», а не на вопрос
  // совместимости, и гонять его тремя движками значило бы платить втрое за
  // тот же ответ.
  use: { baseURL: process.env.E2E_BASE_URL ?? 'http://localhost:4173', headless: true },
  reporter: [['list']],
  // Сервер поднимается только когда адрес не задан снаружи: на CI сайт может
  // быть уже развёрнут, и второй сервер поверх него сбивал бы проверку.
  ...(process.env.E2E_BASE_URL ? {} : {
    webServer: {
      command: 'npm run -w frontend preview -- --port 4173 --strictPort',
      port: 4173,
      reuseExistingServer: true,
      timeout: 120_000,
    },
  }),
})
