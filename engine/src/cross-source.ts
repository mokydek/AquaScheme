/**
 * Перекрёстное подтверждение величины несколькими источниками.
 *
 * Механизм был написан один раз — для глубины промерзания, которую отчёт
 * называет дважды, прозой и таблицей, — и жил внутри разбора геологии, откуда
 * его нельзя было позвать. Второй такой заводить нельзя: два разных ответа на
 * вопрос «подтверждено ли» расходятся молча. Поэтому он вынесен сюда, а разбор
 * геологии пользуется им же.
 *
 * ГЛАВНОЕ ПРАВИЛО: подтверждение считается перекрёстным, только если совпали И
 * ЗНАЧЕНИЕ, И ИЗМЕРЯЕМАЯ ВЕЛИЧИНА. Иначе получается ложное подтверждение — и
 * оно уже едва не попало в проект. По ул. Станкевича Ø450 стоит и в
 * технических условиях, и в акте обследования, но в ТУ это ПРОЕКТНЫЙ диаметр,
 * а в акте — диаметр СУЩЕСТВУЮЩЕЙ трубы. Совпадение означает «проект сохраняет
 * существующий диаметр», а вовсе не «величина подтверждена двумя источниками»,
 * и объявить второе значило бы выдать совпадение за проверку.
 *
 * Источник должен быть НЕЗАВИСИМЫМ. Две записи одной величины в одном и том же
 * месте документа подтверждением не являются: это одно чтение, а не два.
 * Независимость определяет вызывающий, называя источник, — форму записи для
 * геологии, имя файла для документов.
 */

export interface SourceReading<T> {
  /**
   * Что измеряется. Ключ сравнения наравне со значением.
   *
   * Проектный диаметр и диаметр существующей трубы — разные величины, даже
   * когда числа совпадают.
   */
  quantity: string
  value: T
  /** Независимый источник: имя файла, форма записи, документ. */
  source: string
  /** Цитата, по которой величина прочитана. */
  quote: string
  page?: number
  /**
   * Происхождение чтения.
   *
   * Скан обязан оставаться отличимым от цифрового документа и после
   * подтверждения: у ТУ_05-3-2723 текстового слоя нет вовсе, и величина оттуда
   * прочитана распознаванием.
   */
  origin?: string
}

export interface CrossConfirmation<T> {
  quantity: string
  value: T
  /** Все чтения этой величины, по одному на источник. */
  readings: Array<SourceReading<T>>
  /** Независимых источников, назвавших ровно эту величину. */
  sourceCount: number
  /** Источников больше одного. */
  confirmed: boolean
}

/**
 * Ключ сравнения: величина И значение вместе.
 *
 * Отдельной функцией, потому что строится в двух местах и обязан совпадать.
 * Разделитель явный: в названии величины бывает пробел, а собранный «на глаз»
 * ключ однажды уже уехал на невидимый символ.
 */
export function quantityValueKey(quantity: string, value: unknown): string {
  return `${quantity}\u001f${JSON.stringify(value)}`
}

/**
 * Сводит чтения в подтверждения.
 *
 * Ничего не выбирает и ничего не отбрасывает: несколько несовпадающих величин
 * остаются несколькими подтверждениями, и выбирает между ними инженер.
 * Подтверждённые идут первыми — сперва то, что сказано дважды и не разошлось.
 */
export function crossConfirm<T>(readings: ReadonlyArray<SourceReading<T>>): Array<CrossConfirmation<T>> {
  const groups = new Map<string, CrossConfirmation<T>>()
  for (const reading of readings) {
    const key = quantityValueKey(reading.quantity, reading.value)
    const group = groups.get(key)
    if (!group) {
      groups.set(key, {
        quantity: reading.quantity,
        value: reading.value,
        readings: [reading],
        sourceCount: 1,
        confirmed: false,
      })
      continue
    }
    // Повторное чтение из ТОГО ЖЕ источника подтверждением не является: это
    // одно чтение, а не два. В список цитат оно всё равно попадает — документ
    // мог сказать величину в двух местах, и обе цитаты инженеру полезны.
    const known = new Set(group.readings.map((item) => item.source))
    group.readings.push(reading)
    if (!known.has(reading.source)) {
      group.sourceCount += 1
      group.confirmed = true
    }
  }
  return [...groups.values()].sort((left, right) =>
    Number(right.confirmed) - Number(left.confirmed)
    || right.sourceCount - left.sourceCount
    || left.quantity.localeCompare(right.quantity))
}

/**
 * Подтверждено ли конкретное значение величины.
 *
 * Отдельная функция, потому что разбору геологии нужен именно флаг на
 * кандидате, а не сводка: остальную его работу — грунт, единицы, окно поиска —
 * переносить сюда незачем.
 */
export function crossConfirmedValues<T>(
  readings: ReadonlyArray<SourceReading<T>>,
): Set<string> {
  return new Set(
    crossConfirm(readings)
      .filter((group) => group.confirmed)
      .map((group) => quantityValueKey(group.quantity, group.value)),
  )
}
