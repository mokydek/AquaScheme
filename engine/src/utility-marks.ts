/**
 * Разбор марок существующих коммуникаций на топосъёмке.
 *
 * Съёмщик подписывает каждую сеть короткой маркой: `ППУ1020/1200`, `пвх600`,
 * `1каб.10кВ-0.7`, `гильза ст1420`. В этой марке записано то, за чем инженер
 * иначе идёт к владельцу сети: вид коммуникации и её габарит. Пока программа
 * марку не читала, карточка пересечения оставалась пустой, а пустое поле
 * заполняется догадкой — либо не заполняется вовсе.
 *
 * Реестр соответствий построен на марках ЭТОЙ съёмки, а не на общих
 * представлениях: 112 линий коммуникаций, марки выписаны из DXF. Реестр
 * открытый — он показывается инженеру целиком, и марка, которую он не покрыл,
 * не выбрасывается, а попадает в список нераспознанных.
 *
 * Что здесь НЕ выводится, потому что в марке этого нет:
 *   - владелец сети (юридическое лицо) — только из ТУ или запроса;
 *   - материал рабочей трубы там, где марка называет лишь изоляцию;
 *   - глубина заложения. У кабелей за напряжением иногда стоит `-0.7`, и это
 *     очень похоже на глубину в метрах. «Похоже» — не основание: число не
 *     истолковывается, а сохраняется в `unparsedTail`, чтобы инженер увидел
 *     его сам.
 *
 * РАЗДЕЛЕНИЕ С `parsePipeLabel`. Материал и диаметр простой марки вида
 * «материал+число» умеет `existing-utilities.parsePipeLabel`, и он остаётся
 * единственным, кто знает таблицу материалов: здесь он вызывается, а не
 * повторяется. Второй разбор тех же марок означал бы две расходящиеся правды —
 * ровно то, что уже вычищалось из расчёта просветов. Этот модуль добавляет
 * только то, чего тот не умеет: вид сети, пару «труба/оболочка» у ППУ, счётчик
 * пучка, напряжение кабеля и футляр.
 */

import { parsePipeLabel } from './existing-utilities'

export type UtilityKind =
  /** Теплосеть. */
  | 'heat'
  /** Трубопровод, вид сети маркой не назван (марка говорит лишь материал). */
  | 'pipe'
  /** Водопровод. */
  | 'water'
  /** Хозяйственно-бытовая канализация. */
  | 'sewer'
  /** Ливневая канализация. */
  | 'storm'
  /** Газопровод. */
  | 'gas'
  /** Силовой кабель. */
  | 'cable'
  /** Кабель связи. */
  | 'communication'
  /** Футляр или гильза. */
  | 'casing'
  /** Кабельная канализация — короб, а не сама линия. */
  | 'cableDuct'

export interface UtilityMark {
  /** Марка дословно, как подписана в чертеже. */
  raw: string
  /** Вид сети; `null`, когда реестр марку не покрыл. */
  kind: UtilityKind | null
  /** Подстрока марки, по которой определён вид: инженеру видно основание. */
  kindEvidence?: string
  /** Габарит рабочей трубы, мм. */
  sizeMm?: number
  /** Материал — из `parsePipeLabel`, если марка ему поддалась. */
  material?: string
  /** Наружный габарит, мм: у теплосети в ППУ это диаметр оболочки. */
  outerMm?: number
  /** Число труб или кабелей в пучке. */
  count?: number
  /** Напряжение кабеля, кВ. */
  voltageKv?: number
  /**
   * Остаток марки, который не истолкован.
   *
   * Существует ровно для того, чтобы не выбрасывать непонятое молча.
   */
  unparsedTail?: string
}

interface RegistryEntry {
  /** Признак вида в марке. */
  pattern: RegExp
  kind: UtilityKind
  /** Что признак означает — показывается инженеру в таблице реестра. */
  meaning: string
  /** Марка этой съёмки, на которой признак наблюдался. */
  seen: string
}

/**
 * Реестр соответствий «признак марки → вид сети».
 *
 * Порядок значим: более узкий признак стоит раньше общего. «ВОЛС» — раньше
 * «каб», иначе кабель связи стал бы силовым; «гильза» — раньше «ст», иначе
 * футляр стал бы стальной трубой.
 */
export const UTILITY_MARK_REGISTRY: readonly RegistryEntry[] = [
  { pattern: /волс/i, kind: 'communication', meaning: 'волоконно-оптическая линия связи', seen: '1кабВОЛС' },
  { pattern: /гильз|футляр/i, kind: 'casing', meaning: 'футляр (гильза) на переходе', seen: 'гильза ст1420' },
  { pattern: /каб\.?\s*канал/i, kind: 'cableDuct', meaning: 'кабельная канализация — короб, а не линия', seen: 'каб.канал' },
  { pattern: /ппу/i, kind: 'heat', meaning: 'труба в пенополиуретановой изоляции — теплосеть', seen: 'ППУ1020/1200' },
  { pattern: /тепл/i, kind: 'heat', meaning: 'теплосеть названа словом', seen: 'теплотрасса' },
  { pattern: /каб|кв(?![а-яё])/i, kind: 'cable', meaning: 'силовой кабель; напряжение — из «кВ»', seen: '1каб.10кВ-0.7' },
  { pattern: /газ/i, kind: 'gas', meaning: 'газопровод', seen: 'Газопровод подземный' },
  { pattern: /лив/i, kind: 'storm', meaning: 'ливневая канализация', seen: 'кол.Лив' },
  { pattern: /кан(?!ал)/i, kind: 'sewer', meaning: 'хозяйственно-бытовая канализация', seen: 'кол.Кан' },
  { pattern: /вод/i, kind: 'water', meaning: 'водопровод', seen: 'кол.вод.' },
  // «ж/б канал» намеренно исключён: железобетонный канал бывает и кабельным,
  // и под теплосеть — по марке не различить, и догадка здесь хуже прочерка.
  { pattern: /ж\/?б(?!\s*канал)/i, kind: 'pipe', meaning: 'железобетонная труба; вид сети маркой не назван', seen: 'ж/б1600' },
  { pattern: /пвх|пэ(?![а-яё])|пнд|чуг|ст\.?пл|ст(?![а-яё])/i, kind: 'pipe', meaning: 'трубопровод: марка называет материал, вид сети — нет', seen: 'пвх600' },
]

/** Сколько труб или кабелей: ведущее число марки — `2тр.`, `6каб.`, `1каб.`. */
const COUNT = /^(\d)\s*(?:тр|каб)/i

/** Напряжение: число перед «кВ». */
const VOLTAGE = /(\d+(?:[.,]\d+)?)\s*кв(?![а-яё])/i

/** Пара «рабочий/наружный»: у ППУ это труба и оболочка. */
const PAIR = /(\d{2,4})\s*\/\s*(\d{2,4})/

/** Одиночный габарит: число, приросшее к материалу. */
const SINGLE = /(?:^|[^\d])(\d{2,4})(?![\d/])/

/**
 * Габариты наружных сетей, мм.
 *
 * Тот же ряд, что у разбора ТУ: число вне его — не диаметр, а год, номер
 * камеры или отметка. `камера 119` не должна стать трубой Ø119.
 */
const MIN_SIZE_MM = 20
const MAX_SIZE_MM = 3000

const inRange = (value: number): boolean =>
  Number.isFinite(value) && value >= MIN_SIZE_MM && value <= MAX_SIZE_MM

/**
 * Читает марку.
 *
 * Вид не определился — возвращается `kind: null`, и это не ошибка, а честный
 * ответ: такая марка попадает инженеру списком нераспознанных.
 */
export function parseUtilityMark(raw: string): UtilityMark {
  const text = raw.trim()
  const mark: UtilityMark = { raw: text, kind: null }
  if (text === '') return mark

  for (const entry of UTILITY_MARK_REGISTRY) {
    const found = entry.pattern.exec(text)
    if (found) {
      mark.kind = entry.kind
      mark.kindEvidence = found[0]
      break
    }
  }

  const count = COUNT.exec(text)
  if (count) mark.count = Number(count[1])

  const voltage = VOLTAGE.exec(text)
  if (voltage) mark.voltageKv = Number(voltage[1].replace(',', '.'))

  // Габарит берётся ТОЛЬКО у марки с опознанным видом, который габарит несёт.
  //
  // Иначе число вынималось бы из непонятой подписи: `камера 119` давала трубу
  // Ø119, хотя 119 — это номер камеры. Опознанный вид и есть то основание, при
  // котором число рядом с материалом означает диаметр.
  //
  // У кабеля число перед «кВ» — напряжение, а не габарит; габарит кабеля марка
  // не несёт вовсе, и придумывать его нечем.
  const SIZE_BEARING: ReadonlyArray<UtilityKind> = ['heat', 'pipe', 'water', 'sewer', 'storm', 'gas', 'casing']
  const carriesSize = mark.kind !== null && SIZE_BEARING.includes(mark.kind)
  if (carriesSize) {
    const pair = PAIR.exec(text)
    if (pair && inRange(Number(pair[1])) && inRange(Number(pair[2]))) {
      // Пара «труба/оболочка» — форма, которой `parsePipeLabel` не знает.
      mark.sizeMm = Number(pair[1])
      mark.outerMm = Number(pair[2])
    } else {
      // Сначала — существующий разбор: он владеет таблицей материалов.
      // Ведущий счётчик труб ему мешает, поэтому отрезается: `2тр.пвх100` —
      // это две трубы по 100, а не труба Ø2.
      // Точка после счётчика («2тр.пвх100») существующему разбору мешает.
      const body = (count ? text.slice(count[0].length) : text).replace(/^[\s.]+/, '')
      const known = parsePipeLabel(body)
      if (known && inRange(known.diameterMm)) {
        mark.sizeMm = known.diameterMm
        mark.material = known.material
        if (mark.count === undefined && known.count > 1) mark.count = known.count
      } else {
        const single = SINGLE.exec(body)
        if (single && inRange(Number(single[1]))) mark.sizeMm = Number(single[1])
      }
    }
  }

  // Хвост после напряжения кабеля не истолковывается: `-0.7` очень похоже на
  // глубину заложения, но «похоже» основанием не является.
  if (voltage) {
    const tail = text.slice((voltage.index ?? 0) + voltage[0].length).trim()
    if (tail !== '') mark.unparsedTail = tail
  }

  return mark
}
