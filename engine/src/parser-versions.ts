/**
 * Версия разбора: чем получена сохранённая величина.
 *
 * ПОВОД. Три захода подряд чинили извлечение — посев перестал выбирать грунт,
 * геологию начал разбирать слот, ложные кандидаты отсеялись, — и все три на
 * живом объекте выглядели так, будто их не было. Правка извлечения чинит
 * БУДУЩИЕ загрузки; сделанные лежат в базе как были. Владелец открывал проект
 * и видел шесть кандидатов промерзания, включая 2,00 м из таблицы нумерации,
 * потому что разбор был сделан вчерашним кодом, а экран показывает
 * сохранённое.
 *
 * Сказать «эта величина получена устаревшим разбором» программе было нечем:
 * ни в `extracted`, ни в записи набора версии не было. Сохранённый результат
 * неотличим от свежего.
 *
 * ЧЕМ ВЕРСИЯ ЯВЛЯЕТСЯ. Числом, которое поднимают руками. Отпечаток, считаемый
 * из кода, не забывают поднять — но он меняется от переставленной запятой и
 * поднимает ложную тревогу; а предупреждение, которое врёт, перестают читать
 * ровно так же, как молчание. Поэтому номер объявлен здесь, а забыть его не
 * даёт `parser-versions.test.ts`: он держит отпечаток исходника разбора и
 * падает, когда исходник разошёлся с записанным. Автор правки выбирает сам —
 * поднять номер (правка меняет результат) или переписать отпечаток (правка
 * косметическая). Платим одним осознанным шагом на каждую правку разбора.
 *
 * У КАЖДОГО РАЗБОРА СВОЯ. Правка разбора геологии не делает устаревшим разбор
 * акта обследования: это разные документы, разные извлекатели и разные
 * величины. Общая версия объявила бы устаревшим всё сразу — и научила бы не
 * верить предупреждению в третий раз.
 */

/**
 * Действующие версии разборов, по идентификатору документа в наборе basis.
 *
 * ПОДНИМАТЬ, когда меняется РЕЗУЛЬТАТ разбора: новые поля, другой отбор,
 * исправленное чтение величин. Не поднимать за переименование переменной или
 * правку комментария — для этого в проверке отпечатка есть второй выход.
 */
export const PARSER_VERSIONS = {
  /**
   * 1 → 2: кандидатом промерзания стало только то, что записано как глубина.
   * Голое целое меньше двадцати без единицы — номер столбца, а не метры; такие
   * строки уехали в отдельный список `freezingDepthUnitlessRows`.
   */
  geology: 2,
  /** 1: первая версия; величины акта технического обследования с цитатами. */
  survey_act: 1,
} as const

/** Документ, у разбора которого есть версия. */
export type ParsedDocumentId = keyof typeof PARSER_VERSIONS

/**
 * Возраст сохранённого разбора относительно действующего.
 *
 * ОТСУТСТВИЕ ВЕРСИИ — ЭТО «НЕИЗВЕСТНО», А НЕ «СВЕЖИЙ». В базе владельца две
 * записи без версии: они сделаны до того, как версия появилась, и утверждать
 * про них что-либо нельзя. Разница выражена отдельным видом значения, а не
 * подстановкой нуля или текущего номера.
 */
export type ExtractionAge =
  /** Разбор сделан действующей версией. */
  | { kind: 'current'; currentVersion: number }
  /** Разбор старше действующего: обе величины названы. */
  | { kind: 'outdated'; storedVersion: number; currentVersion: number }
  /** Версии в записи нет: чем получено — неизвестно. */
  | { kind: 'unknown'; currentVersion: number }
  /**
   * Разбор новее действующего: запись сделана более поздней сборкой.
   *
   * Бывает, когда вкладка открыта со старым кодом, а другой сеанс уже
   * перезапустил разбор. Молчать нельзя: экран показывает величины, которых
   * этот код не умеет читать.
   */
  | { kind: 'ahead'; storedVersion: number; currentVersion: number }

/** Версия, записанная вместе с результатом; `null` — её там нет. */
export function storedParserVersion(extraction: unknown): number | null {
  if (typeof extraction !== 'object' || extraction === null || Array.isArray(extraction)) return null
  const value = (extraction as { parserVersion?: unknown }).parserVersion
  return typeof value === 'number' && Number.isFinite(value) ? value : null
}

/**
 * Сравнивает сохранённый разбор с действующим.
 *
 * `null` — разбора этого документа нет вовсе: сказать нечего, и говорить
 * не о чем. Это не то же самое, что разбор без версии.
 */
export function extractionAge(itemId: ParsedDocumentId, extraction: unknown): ExtractionAge | null {
  if (typeof extraction !== 'object' || extraction === null || Array.isArray(extraction)) return null
  const currentVersion = PARSER_VERSIONS[itemId]
  const storedVersion = storedParserVersion(extraction)
  if (storedVersion === null) return { kind: 'unknown', currentVersion }
  if (storedVersion < currentVersion) return { kind: 'outdated', storedVersion, currentVersion }
  if (storedVersion > currentVersion) return { kind: 'ahead', storedVersion, currentVersion }
  return { kind: 'current', currentVersion }
}
