/**
 * Атрибуты обводки для роли.
 *
 * Возвращается готовая строка атрибутов SVG, чтобы перевод «миллиметры →
 * единицы холста» жил в одном месте: разъехавшиеся толщины на разных листах
 * ловятся здесь, а не глазом по PDF.
 */
export function planStroke(role: PlanLineRole, svgUnitsPerMm: number): string {
  const style = PLAN_LINE_STYLE[role]
  const width = style.widthMm * svgUnitsPerMm
  const dash = style.dashMm
    ? ` stroke-dasharray="${(style.dashMm[0] * svgUnitsPerMm).toFixed(2)} ${(style.dashMm[1] * svgUnitsPerMm).toFixed(2)}"`
    : ''
  return `stroke="${style.colour}" stroke-width="${width.toFixed(3)}"${dash}`
}

/** Цвет роли — для подписей, которые набираются цветом своей линии. */
export function planColour(role: PlanLineRole): string {
  return PLAN_LINE_STYLE[role].colour
}

/** Кегль подписи в единицах холста. */
export function planFontSize(svgUnitsPerMm: number, heightMm = PLAN_TEXT_HEIGHT_MM): number {
  return heightMm * svgUnitsPerMm
}

/**
 * Точки повтора буквенной марки вдоль ломаной.
 *
 * Марка ставится не в середине линии, а через равный шаг по её длине — так она
 * читается на любом отрезке, попавшем в окно листа, включая случай, когда
 * середина линии осталась на соседнем листе. Возвращается точка и угол сегмента,
 * чтобы марка легла вдоль линии.
 *
 * Первая марка отступает на половину шага: марка вплотную к началу отрезка
 * налезала бы на узел или на край листа.
 */
export function markPositionsAlong(
  points: ReadonlyArray<{ x: number; y: number }>,
  intervalUnits: number,
): Array<{ x: number; y: number; angleDeg: number }> {
  if (points.length < 2 || !(intervalUnits > 0)) return []
  const out: Array<{ x: number; y: number; angleDeg: number }> = []
  let travelled = 0
  let next = intervalUnits / 2
  for (let index = 1; index < points.length; index++) {
    const from = points[index - 1]
    const to = points[index]
    const length = Math.hypot(to.x - from.x, to.y - from.y)
    if (!(length > 0)) continue
    let angle = Math.atan2(to.y - from.y, to.x - from.x) * 180 / Math.PI
    // Марка не читается вверх ногами: направление разворачивается, положение нет.
    if (angle > 90 || angle < -90) angle += 180
    while (next <= travelled + length) {
      const ratio = (next - travelled) / length
      out.push({
        x: from.x + (to.x - from.x) * ratio,
        y: from.y + (to.y - from.y) * ratio,
        angleDeg: angle,
      })
      next += intervalUnits
    }
    travelled += length
  }
  return out
}
