  // Цвет измерен по эталону, стр. 29: #b85c00, 353 обводки и 699 заливок —
  // тем же цветом набрана марка «Кд», то есть линия и марка одного цвета.
  existingUtility: { widthMm: 0.127, colour: '#b85c00' },
  // ГОСТ 21.704 п.3.9 абз. 4: существующие здания и сооружения — тонкой линией.
  existingBuilding: { widthMm: 0.127, colour: '#000000' },
  // Красная линия: ГОСТ 21.704 знака для неё не даёт. Измерено по эталону,
