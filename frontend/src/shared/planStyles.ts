  redLine: { widthMm: 0.127, colour: '#ff0000' },
  // ГОСТ 21.704 п.3.9 абз. 2: «Видимые участки проектируемых трубопроводов
  // изображают сплошной толстой основной линией».
  //
  // 0,99 мм — самая широкая обводка эталона, и она ровно одна на лист: на
  // стр. 29 это #ff7e00 2,82 pt, на стр. 15 — #0000ff 2,82 pt, то есть сама
  // проектируемая нитка. Первое измерение приписало ей 0,254 мм — это была
  // ошибка отбора: 0,72 pt берётся на подписях и мелких построениях, а нитку я
  // в гистограмму обводок не выделил. Цвет эталона между листами не совпадает,
  // поэтому подтверждена измерением ТОЛЬКО ширина; цвет остаётся наш.
  designedPipe: { widthMm: 0.99, colour: '#1746b5' },
  // Там же: «невидимые — штриховой линией той же толщины».
