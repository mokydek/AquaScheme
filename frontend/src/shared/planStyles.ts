  stationTick: { widthMm: 0.508, colour: '#ffff00' },
  // Кресты сетки: измерено по эталону, стр. 29 и 15 — #0000ff, 0,36 pt.
  coordinateGrid: { widthMm: 0.127, colour: '#0000ff' },
  contour: { widthMm: 0.127, colour: '#8a6b3d' },
  contourIndex: { widthMm: 0.254, colour: '#8a6b3d' },
  corridor: { widthMm: 0.127, colour: '#d33232', dashMm: [3, 2] },
  water: { widthMm: 0.254, colour: '#2685b5' },
  road: { widthMm: 0.254, colour: '#000000' },
